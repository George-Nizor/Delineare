// Copies the Instrumenta brand files Delineare uses, so the app builds and runs on its own.
//
//   npm run brand                    (expects the Instrumenta checkout beside this one)
//   INSTRUMENTA=/path/to/Instrumenta npm run brand
//
// What it copies, and from which Instrumenta commit, is written to public/brand/SOURCE.txt.
// Never edit the copied files; change them in Instrumenta, rebuild there, and run this again.
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const instrumenta = path.resolve(process.env.INSTRUMENTA || path.join(root, '..', 'Instrumenta'));
const brand = path.join(instrumenta, 'brand');
if (!fs.existsSync(path.join(brand, 'icons', 'instrumenta-icons.js'))) {
  throw new Error(`No Instrumenta brand folder at ${brand}. Set INSTRUMENTA to the checkout.`);
}

const copy = (from, to) => {
  fs.mkdirSync(path.dirname(to), { recursive: true });
  fs.copyFileSync(from, to);
  return path.relative(root, to);
};
const copied = [];

// Type: the three brand faces with their licences.
const fonts = path.join(root, 'public', 'fonts');
for (const name of fs.readdirSync(path.join(brand, 'fonts'))) {
  if (/\.(woff2|css|txt)$/.test(name)) copied.push(copy(path.join(brand, 'fonts', name), path.join(fonts, 'brand', name)));
}


// The mark: static icons for the favicon and the Windows shortcut, plus rendered SVG strings
// the interface inserts itself, with the library's motion CSS.
const icons = path.join(brand, 'icons');
for (const file of ['svg/delineare.svg', 'svg/delineare-24.svg', 'svg/delineare-16.svg', 'svg/delineare-animated.svg', 'png/delineare-32.png', 'png/delineare-192.png', 'png/delineare-512.png', 'png/delineare-256.png', 'ico/delineare.ico']) {
  if (fs.existsSync(path.join(icons, file))) copied.push(copy(path.join(icons, file), path.join(root, 'public', 'brand', path.basename(file))));
}
copied.push(copy(path.join(icons, 'instrumenta-icons.css'), path.join(root, 'src', 'brand', 'instrumenta-icons.css')));
const library = createRequire(import.meta.url)(path.join(icons, 'instrumenta-icons.js'));
const marks = Object.fromEntries([16, 24, 32, 48, 96].map((size) => [size, library.render('delineare', { size, label: '' })]));
const colours = library.colours('delineare');
fs.writeFileSync(path.join(root, 'src', 'brand', 'mark.ts'), `// Generated by scripts/sync-brand.mjs from Instrumenta's icon library. Do not edit.\n// Presentation attributes only, so it is safe under a CSP that forbids inline styles.\n\nexport const MARK: Record<number, string> = ${JSON.stringify(marks, null, 2)};\n\nexport const COLOURS = ${JSON.stringify(colours, null, 2)} as const;\n`);
copied.push('src/brand/mark.ts');

const tokens = JSON.parse(fs.readFileSync(path.join(brand, 'tokens.json'), 'utf8'));
fs.writeFileSync(path.join(root, 'src', 'brand', 'tokens.json'), `${JSON.stringify({ family: tokens.family, delineare: tokens.delineare }, null, 2)}\n`);
copied.push('src/brand/tokens.json');

let commit = 'unknown';
try { commit = execFileSync('git', ['-C', instrumenta, 'rev-parse', '--short', 'HEAD'], { encoding: 'utf8' }).trim(); } catch { /* not a checkout */ }
fs.mkdirSync(path.join(root, 'public', 'brand'), { recursive: true });
fs.writeFileSync(path.join(root, 'public', 'brand', 'SOURCE.txt'), `Copied from Instrumenta ${commit} by scripts/sync-brand.mjs on ${new Date().toISOString().slice(0, 10)}.\n\n${copied.sort().join('\n')}\n`);
console.log(`Copied ${copied.length} brand files from Instrumenta ${commit}.`);
